// Reads a built .wasm + the Emscripten JS glue and rewrites them into
// TypeScript source files committed under src/.
//
// The .wasm is gzipped and base64-encoded; the JS glue is converted
// into an ES module by wrapping the IIFE-style Emscripten output and
// exposing the factory function as the default export.

import { Buffer } from 'node:buffer';
import { readFileSync, writeFileSync } from 'node:fs';
import { argv } from 'node:process';

function parseArgs() {
  const args = {};
  for (let i = 2; i < argv.length; i += 2) {
    const key = argv[i];
    const value = argv[i + 1];
    if (!key?.startsWith('--') || value === undefined) {
      throw new Error(`Bad arg: ${key}`);
    }
    args[key.slice(2)] = value;
  }
  return args;
}

async function gzipWithCompressionStream(bytes) {
  const stream = new Blob([bytes])
    .stream()
    .pipeThrough(new CompressionStream('gzip'));
  return new Uint8Array(await new Response(stream).arrayBuffer());
}

const args = parseArgs();
const wasmPath = args.wasm;
const gluePath = args.glue;
const outDataPath = args['out-data'];
const outGluePath = args['out-glue'];

if (!wasmPath || !gluePath || !outDataPath || !outGluePath) {
  throw new Error(
    'usage: embed-wasm.js --wasm <path> --glue <path> --out-data <path> --out-glue <path>',
  );
}

const wasmBytes = new Uint8Array(readFileSync(wasmPath));
const gzipped = await gzipWithCompressionStream(wasmBytes);
const base64 = Buffer.from(gzipped).toString('base64');

const dataModule = `// This file is auto-generated by build/embed-wasm.js. Do not edit by hand.
// Run \`npm run build-wasm\` to regenerate.
//
// The InChI WebAssembly module compiled from vendor/inchi (IUPAC InChI C
// library, MIT) plus build/inchi_web.c (IUPAC, MIT). The binary is
// gzip-compressed and base64-encoded so the npm package is fully
// self-contained — no fetch and no external .wasm file.

export const wasmBase64 =
  '${base64}';
`;

writeFileSync(outDataPath, dataModule);

const glueSource = readFileSync(gluePath, 'utf8');

// Emscripten with -sMODULARIZE produces code that ends in:
//   if (typeof exports === 'object' && typeof module === 'object') module.exports = inchiModule;
//   else if (typeof define === 'function' && define['amd']) ...
//   else if (typeof exports === 'object') exports["inchiModule"] = inchiModule;
//
// We strip those UMD trailers and export the factory directly.
const moduleName = 'inchiModule';

let cleaned = glueSource;
// Strip the UMD trailer Emscripten appends after the closure. It
// looks like `;if(typeof exports==="object"...{module.exports=inchiModule;
// module.exports.default=inchiModule}else if(typeof define...)...`
// and may or may not be preceded by a newline.
const umdIndex = cleaned.search(/;if\s*\(typeof exports[\s\S]*?$/u);
if (umdIndex !== -1) {
  cleaned = `${cleaned.slice(0, umdIndex)};`;
}

const glueModule = `// This file is auto-generated by build/embed-wasm.js. Do not edit by hand.
// Run \`npm run build-wasm\` to regenerate.
//
// Emscripten-generated JS glue for the InChI WebAssembly module, wrapped
// as an ES module that exposes the factory function as the default
// export. The factory accepts an options bag including \`wasmBinary\` so
// the WASM bytes are passed in directly (no fetch).

/* eslint-disable */
// @ts-nocheck

${cleaned}

export default ${moduleName};
`;

writeFileSync(outGluePath, glueModule);
